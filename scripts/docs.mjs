#!/usr/bin/env node
// Docs index generator and checker. Schema and rules: docs/README.md.
// Usage: node scripts/docs.mjs index   (rewrite INDEX.md files)
//        node scripts/docs.mjs check   (validate, fail if indexes are stale)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"

const ROOT = resolve(import.meta.dirname, "..")
const DOCS = join(ROOT, "docs")
const MAX_LINES = 300
const MAX_SUMMARY = 140
const SECTIONS = {
  "": { prefix: "DOC", types: ["guide"], statuses: ["active"] },
  designs: {
    prefix: "DES",
    title: "Designs",
    holds: "system designs and UI instructions",
    types: ["design", "ui"],
    statuses: ["draft", "active", "deprecated"],
  },
  backlogs: {
    prefix: "BL",
    title: "Backlogs",
    holds: "chunked work items, one per file",
    types: ["backlog"],
    statuses: ["todo", "doing", "blocked", "done"],
  },
}
const KEYS = [
  "id",
  "title",
  "type",
  "status",
  "summary",
  "tags",
  "related",
  "updated",
]
const BACKLOG_KEYS = ["priority", "depends"]
const LISTS = ["tags", "related", "depends"]
const PRIORITIES = ["P0", "P1", "P2"]
const GENERATED =
  "<!-- Generated by `pnpm docs:index` from frontmatter. Do not edit. -->"

const errors = []
const fail = (file, msg) => errors.push(`${relative(ROOT, file)}: ${msg}`)

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name)
    if (e.isDirectory()) return walk(p)
    return e.name.endsWith(".md") ? [p] : []
  })
}

// Frontmatter is a strict YAML subset: `key: value` or `key: [a, b]`.
function parseFrontmatter(file, text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/)
  if (!m) return (fail(file, "missing frontmatter"), null)
  const meta = {}
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([a-z]+): (.*)$/)
    if (!kv) {
      fail(file, `bad frontmatter line: ${line}`)
      continue
    }
    let [, key, value] = kv
    value = value.trim()
    if (LISTS.includes(key)) {
      const list = value.match(/^\[(.*)\]$/)
      if (!list) fail(file, `${key} must be an inline list like [a, b]`)
      meta[key] = list
        ? list[1]
            .split(",")
            .map((s) => s.trim())
            .filter(Boolean)
        : []
    } else {
      meta[key] = value.replace(/^"(.*)"$/, "$1")
    }
  }
  return meta
}

const docs = []
for (const file of walk(DOCS)) {
  const text = readFileSync(file, "utf8")
  const lines = text.split("\n").length - (text.endsWith("\n") ? 1 : 0)
  if (lines > MAX_LINES) fail(file, `${lines} lines, max ${MAX_LINES}`)

  for (const [, target] of text.matchAll(/\]\(([^)\s]+)\)/g)) {
    if (/^[a-z]+:/.test(target) || target.startsWith("#")) continue
    const path = resolve(dirname(file), target.split("#")[0])
    if (!existsSync(path)) fail(file, `broken link: ${target}`)
  }

  const rel = relative(DOCS, file)
  if (rel === "INDEX.md" || rel.endsWith("/INDEX.md")) continue
  const sectionName = rel.includes("/") ? rel.split("/")[0] : ""
  const section = SECTIONS[sectionName]
  if (!section || rel.split("/").length > 2) {
    fail(file, "docs live in docs/, docs/designs/ or docs/backlogs/ only")
    continue
  }
  const meta = parseFrontmatter(file, text)
  if (!meta) continue

  const allowed = meta.type === "backlog" ? [...KEYS, ...BACKLOG_KEYS] : KEYS
  for (const k of allowed) if (!(k in meta)) fail(file, `missing ${k}`)
  for (const k of Object.keys(meta))
    if (!allowed.includes(k)) fail(file, `unknown key ${k}`)
  if (!new RegExp(`^${section.prefix}-\\d{3}$`).test(meta.id ?? ""))
    fail(file, `id must look like ${section.prefix}-001`)
  const base = file.split("/").pop()
  if (
    meta.id &&
    rel !== "README.md" &&
    !base.startsWith(`${meta.id.toLowerCase()}-`)
  )
    fail(file, `file name must start with ${meta.id?.toLowerCase()}-`)
  if (!section.types.includes(meta.type))
    fail(file, `type must be one of ${section.types}`)
  if (!section.statuses.includes(meta.status))
    fail(file, `status must be one of ${section.statuses}`)
  if (!meta.summary || meta.summary.length > MAX_SUMMARY)
    fail(file, `summary required, max ${MAX_SUMMARY} chars`)
  if (!meta.tags?.length) fail(file, "at least one tag")
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.updated ?? ""))
    fail(file, "updated must be YYYY-MM-DD")
  if (meta.type === "backlog") {
    if (!PRIORITIES.includes(meta.priority))
      fail(file, `priority must be one of ${PRIORITIES}`)
    if (!/^## Done when$/m.test(text))
      fail(file, 'backlog needs a "## Done when" section')
  }
  docs.push({ ...meta, file, section: sectionName })
}

const byId = new Map()
for (const d of docs) {
  if (byId.has(d.id)) fail(d.file, `duplicate id ${d.id}`)
  byId.set(d.id, d)
}
for (const d of docs) {
  for (const r of d.related ?? [])
    if (!byId.has(r)) fail(d.file, `related ${r} not found`)
  for (const r of d.depends ?? [])
    if (!byId.get(r) || byId.get(r).type !== "backlog")
      fail(d.file, `depends ${r} is not a backlog`)
}

const cell = (s) => String(s).replaceAll("|", "\\|")
const link = (d, from) => `[${cell(d.title)}](${relative(from, d.file)})`
const sorted = (name) =>
  docs
    .filter((d) => d.section === name)
    .sort((a, b) => a.id.localeCompare(b.id))

function sectionIndex(name) {
  const s = SECTIONS[name]
  const dir = join(DOCS, name)
  const rows = sorted(name)
  const backlog = name === "backlogs"
  const head = backlog
    ? "| ID | Status | Pri | Depends | Title | Summary | Tags |\n| --- | --- | --- | --- | --- | --- | --- |"
    : "| ID | Type | Status | Title | Summary | Tags |\n| --- | --- | --- | --- | --- | --- |"
  const body = rows.map((d) =>
    backlog
      ? `| ${d.id} | ${d.status} | ${d.priority} | ${d.depends.join(", ") || "-"} | ${link(d, dir)} | ${cell(d.summary)} | ${d.tags.join(", ")} |`
      : `| ${d.id} | ${d.type} | ${d.status} | ${link(d, dir)} | ${cell(d.summary)} | ${d.tags.join(", ")} |`
  )
  return `${GENERATED}\n\n# ${s.title} index\n\nHolds ${s.holds}. Back to [docs index](../INDEX.md).\n\n${head}\n${body.join("\n")}\n`
}

function rootIndex() {
  const guides = sorted("").map(
    (d) => `| ${d.id} | ${link(d, DOCS)} | ${cell(d.summary)} |`
  )
  const sections = ["designs", "backlogs"].map((n) => {
    const rows = sorted(n)
    const open =
      n === "backlogs"
        ? `, ${rows.filter((d) => d.status !== "done").length} open`
        : ""
    return `| ${SECTIONS[n].title} | [${n}/INDEX.md](${n}/INDEX.md) | ${rows.length} docs${open} | ${SECTIONS[n].holds} |`
  })
  return [
    GENERATED,
    "",
    "# Docs index",
    "",
    "Start here. Then open one section index, then only the doc you need.",
    "Schema and retrieval rules: [README.md](README.md).",
    "",
    "| Section | Index | Size | Holds |",
    "| --- | --- | --- | --- |",
    ...sections,
    "",
    "| ID | Guide | Summary |",
    "| --- | --- | --- |",
    ...guides,
    "",
  ].join("\n")
}

const outputs = {
  [join(DOCS, "INDEX.md")]: rootIndex(),
  [join(DOCS, "designs", "INDEX.md")]: sectionIndex("designs"),
  [join(DOCS, "backlogs", "INDEX.md")]: sectionIndex("backlogs"),
}
const mode = process.argv[2] ?? "check"
// Indexes skip prettier (see .prettierignore) so tables stay unpadded.
for (const [file, raw] of Object.entries(outputs)) {
  const text = raw
  if (mode === "index") writeFileSync(file, text)
  else if (!existsSync(file) || readFileSync(file, "utf8") !== text)
    fail(file, "stale, run `pnpm docs:index`")
}

if (errors.length) {
  console.error(
    `docs: ${errors.length} problem(s)\n${errors.map((e) => `  ${e}`).join("\n")}`
  )
  process.exit(1)
}
console.log(
  `docs: ${docs.length} docs ok${mode === "index" ? ", indexes written" : ""}`
)
